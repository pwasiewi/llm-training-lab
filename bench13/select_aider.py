#!/usr/bin/env python3
"""select_aider.py — reproducible Aider Polyglot HARD subset for bench_13.

Source of per-exercise public results (aider itself publishes only totals):
little-coder (github.com/itayinbarr/little-coder, commit 424f7a4b9f),
benchmarks/results_full_polyglot_run{1,2,3}.json — all 225 exercises:
  run 3 = Qwen3.6-35B-A3B UD-Q4_K_M (177/225), runs 1-2 = Qwen3.5-9B (104, 101).

Rule (target: exercises solved by ~30-70 % of similar models):
  band     : solved in exactly 1 or 2 of the 3 public runs (33 % / 67 %)
  tier A   : ... and the Qwen3.6-35B-A3B run did NOT pass on the first try
             (pass_2 or fail) — hard for our 35B-A3B class, not just for 9B
  tier B   : ... Qwen3.6 pass_1 but slow (>= 300 s) — the next-hardest
  skip     : Qwen3.6 time > 1500 s (wall-clock budget)
  quota    : cpp 3, go 4, java 3, javascript 4, python 3, rust 3 = 20
  order    : tier A before B; inside a tier the cheaper (shorter Qwen3.6 time) first
  exclude  : EXCLUDE below (reference solution cannot pass under aider's harness)

Known bias (research/25 B13-12): 16/20 exercises are here because ONE
Qwen3.6-35B-A3B run (little-coder agent, not aider) missed them on try 1, and
tier B selects on that run's wall time. Single-run misses partly regress on
re-run for Qwen3.6-derived models (Ornith 1.5, Tiel, Qwen3.8 distills) but not
for gpt-oss: read cross-FAMILY aider differences as biased by construction;
within-family comparisons are fine. Polyglot (public since 2024-12) is also
contaminated unequally across families. Unbiased alternative: a fixed random
sample per language with a published seed.

Usage: select_aider.py RUN1.json RUN2.json RUN3.json [OUT_TSV]
Writes "lang/exercise<TAB>reason" lines.
"""
import json
import sys

# exercises whose reference solution cannot pass under aider's harness
# (verified with the bench_13 mock oracle, 2026-10-02) — not a fair test
EXCLUDE = {
    "rust/robot-name": "reference imports the rand crate, but aider never lets the model edit Cargo.toml",
}
QUOTA = {"cpp": 3, "go": 4, "java": 3, "javascript": 4, "python": 3, "rust": 3}
MAX_T, SLOW_T = 1500.0, 300.0


def load(path: str) -> dict:
    d = json.load(open(path))
    out = {}
    for lang, x in d["languages"].items():
        for e in x["details"]:
            out[(lang, e["name"])] = (e["status"], float(e.get("time") or 0))
    return out


def main() -> int:
    if len(sys.argv) < 4 or sys.argv[1] in ("-h", "--help"):
        print(__doc__)
        return 0
    r1, r2, r3 = (load(p) for p in sys.argv[1:4])
    rows = []
    for key, (s3, t3) in r3.items():
        s = [r1.get(key, ("fail", 0))[0], r2.get(key, ("fail", 0))[0], s3]
        npass = sum(x.startswith("pass") for x in s)
        if npass not in (1, 2) or t3 > MAX_T or f"{key[0]}/{key[1]}" in EXCLUDE:
            continue
        if s3 != "pass_1":
            tier = "A"
        elif t3 >= SLOW_T:
            tier = "B"
        else:
            continue
        rows.append((key, tier, t3, s, npass))
    out = ["# bench_13 Aider Polyglot HARD subset — generated by select_aider.py",
           "# source: little-coder per-exercise results (Qwen3.6-35B-A3B run3; Qwen3.5-9B runs 1-2)",
           "# BIAS: selected on ONE Qwen3.6 run's misses -> cross-family (Qwen-derived vs gpt-oss) aider",
           "#   differences are biased by construction; compare within a family only (research/25 B13-12)",
           "# columns: lang/exercise<TAB>reason"]
    total = 0
    for lang, q in QUOTA.items():
        cand = sorted((r for r in rows if r[0][0] == lang), key=lambda r: (r[1], r[2]))
        for (l, name), tier, t3, s, npass in cand[:q]:
            out.append(f"{l}/{name}\ttier {tier}: solved in {npass}/3 public runs "
                       f"(Qwen3.6-35B-A3B {s[2]} in {t3:.0f}s; Qwen3.5-9B {s[0]}/{s[1]})")
            total += 1
        if len(cand) < q:
            print(f"WARNING: {lang}: only {len(cand)} candidates for quota {q}", file=sys.stderr)
    out += [f"#X {k}\texcluded: {why}" for k, why in EXCLUDE.items()]
    text = "\n".join(out) + "\n"
    if len(sys.argv) > 4:
        open(sys.argv[4], "w").write(text)
    else:
        sys.stdout.write(text)
    print(f"selected {total}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
