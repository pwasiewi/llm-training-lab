#!/usr/bin/env python3
"""select_swe_screen.py — reproducible SWE-rebench SCREEN selection for bench_13.

Pool: HF nebius/SWE-rebench-leaderboard split 2026_03, Python tasks created
2026-05-01 or later (= the site's May 1-15 2026 Python bucket, 21 tasks).

SWE-rebench publishes no per-task results (only half-month bucket rates), so
the per-task "medium difficulty" filter uses the gold-patch size proxy:
  10 <= added lines <= 50, files changed <= 5, problem statement <= 6000 chars.
13 tasks pass; the one with the largest unshared image (pygeoapi, +1.1 GB vs
~0.3 GB for the rest) is kept as the first reserve, giving 12.

Decontamination: a task is "fresh" only for models released BEFORE it was
created. FLEET_CUTOFF must be the newest release date (HF repo creation)
among the models this screen will rank; 2026-05-01 covers the Qwen3.6
generation only — Ornith 1.5, Tiel, Qwen3.8 were released ~4 months later
and Nebius publishes SWE-rebench tasks as training data. Override with
B13_FLEET_CUTOFF=YYYY-MM-DD (a later split/parquet is then needed: this one
ends 2026-05-12).

Usage: select_swe_screen.py PARQUET [OUT_TSV]
Writes "instance_id<TAB>reason" lines (OUT_TSV default: stdout).
"""
import os
import re
import sys

import pandas as pd

MIN_ADD, MAX_ADD, MAX_FILES, MAX_PS = 10, 50, 5, 6000
# newest release date among the models this screen will rank (HF repo creation date);
# tasks created before it may be in that model's training data
FLEET_CUTOFF = os.environ.get("B13_FLEET_CUTOFF", "2026-05-01")   # TODO: set from the fleet's release dates
RESERVE_FIRST = {"geopython__pygeoapi-2338": "reserve: largest image (2.15 GB, ~1.1 GB unshared)"}


def features(patch: str) -> tuple[int, int, int]:
    files = len(re.findall(r"^diff --git", patch, re.M))
    add = len(re.findall(r"^\+(?!\+\+)", patch, re.M))
    rem = len(re.findall(r"^-(?!--)", patch, re.M))
    return files, add, rem


def main() -> int:
    if len(sys.argv) < 2 or sys.argv[1] in ("-h", "--help"):
        print(__doc__)
        return 0
    df = pd.read_parquet(sys.argv[1])
    df = df[df.created_at >= FLEET_CUTOFF].sort_values("instance_id")
    if FLEET_CUTOFF <= "2026-05-01":
        print(f"WARNING: FLEET_CUTOFF {FLEET_CUTOFF} is post-cutoff only for the Qwen3.6 generation; "
              "later fleet models (Ornith 1.5, Tiel, Qwen3.8) may have seen these merged PRs", file=sys.stderr)
    keep, reserve, out = [], [], []
    for _, r in df.iterrows():
        files, add, rem = features(r.patch)
        ps = len(r.problem_statement)
        desc = (f"gold +{add}/-{rem} lines, {files} file(s), F2P {len(r.FAIL_TO_PASS)}, "
                f"P2P {len(r.PASS_TO_PASS)}, statement {ps} ch"
                + (", interface spec given" if (r.interface or "").strip() else "")
                + f", created {r.created_at[:10]}")
        if not (MIN_ADD <= add <= MAX_ADD):
            reserve.append((r.instance_id, f"excluded: patch size ({desc})"))
        elif files > MAX_FILES:
            reserve.append((r.instance_id, f"excluded: too many files ({desc})"))
        elif ps > MAX_PS:
            reserve.append((r.instance_id, f"excluded: statement too long ({desc})"))
        elif r.instance_id in RESERVE_FIRST:
            reserve.append((r.instance_id, f"{RESERVE_FIRST[r.instance_id]} ({desc})"))
        else:
            keep.append((r.instance_id, f"medium by patch-size proxy ({desc})"))
    out.append("# bench_13 SWE-rebench SCREEN set — generated by select_swe_screen.py")
    out.append(f"# pool: 2026_03 split, Python, created >= {FLEET_CUTOFF} ({len(df)}); public bucket rate for this pool:")
    out.append("#   Qwen3.6-35B-A3B 30.5 % pass@1 / 47.6 % pass@5 (swe-rebench.com rangeStats, May 1-15 2026)")
    out.append(f"# CONTAMINATION: fresh only for models released before {FLEET_CUTOFF} (Qwen3.6 generation);")
    out.append("#   Ornith 1.5 / Tiel / Qwen3.8 are later and SWE-rebench tasks are published as training data")
    out.append("# columns: instance_id<TAB>reason   (lines starting with '#' = comments; '#R ' = not selected)")
    out += [f"{i}\t{why}" for i, why in keep]
    out += [f"#R {i}\t{why}" for i, why in reserve]
    text = "\n".join(out) + "\n"
    if len(sys.argv) > 2:
        open(sys.argv[2], "w").write(text)
    else:
        sys.stdout.write(text)
    print(f"selected {len(keep)}, not selected {len(reserve)}", file=sys.stderr)
    return 0


if __name__ == "__main__":
    sys.exit(main())
